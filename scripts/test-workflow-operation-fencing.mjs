import assert from 'node:assert/strict';
import { reset, redis, refetch, post, request, fetchCurrent, confirm, read, fake, leases, order } from './fakes/m1-workflow-fixture.mjs';
await reset(); const input=await request();
const owner=await leases.acquireWorkflowLease('refetch',null);
assert.equal((await post(refetch,input)).status,409);
await leases.releaseWorkflowLease(owner);
await fetchCurrent(); await confirm();
const first=await request(); const gate=fake.installWorkflowOrderListGate();
const inFlight=post(refetch,first); await gate.entered;
await redis.del('orders:workflow_operation_lease');
fake.setWorkflowBaseOrders([order('A')]);
const second=await request(); assert.equal((await post(refetch,second)).status,200);
const winner=await redis.getRawString('orders:refetch_state');
const attempt=await redis.getRawString('orders:refetch_attempt');
gate.release(); assert.equal((await inFlight).status,409);
assert.equal(await redis.getRawString('orders:refetch_state'),winner);
assert.equal(await redis.getRawString('orders:refetch_attempt'),attempt);
assert.equal((await post(refetch,first)).status,409);
assert.equal((await read('orders:refetch_attempt')).request_id,second.request_id);
assert.equal(await redis.compareAndDelete('orders:workflow_operation_lease',owner.serialized),false);
console.log('M1 fencing: mutual exclusion, expired owner, late response, superseded request passed');
